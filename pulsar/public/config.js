// NOTE: this is most likely not needed for anybody who doesn't use ton or is putting this on their own site. im only doing this because it's useful and so i dont have to manually add each ton link to the wisp urls
(function addSelfWispUrl() {
    const config = window.__PULSAR_CONFIG__;

    function parseOrigin(value) {
        if (typeof value !== "string" || value === "" || value === "null") return null;
        const candidate = value.startsWith("blob:") ? value.slice(5) : value;
        let url;
        try {
            url = new URL(candidate);
        } catch {
            return null;
        }
        if (url.protocol !== "http:" && url.protocol !== "https:") return null;
        if (!url.host) return null;
        return url;
    }

    function resolveOrigin() {
        const ancestors = window.location.ancestorOrigins;
        const sources = [
            window.location.origin,
            window.location.href,
            ancestors && ancestors.length ? ancestors[ancestors.length - 1] : null,
            document.referrer,
        ];
        for (const source of sources) {
            const url = parseOrigin(source);
            if (url) return url;
        }
        return null;
    }

    const origin = resolveOrigin();
    if (!origin) return;
    // A local static server does not expose a Wisp endpoint at /w. Do not
    // add a guaranteed-failing localhost socket before the real fallbacks.
    if (origin.hostname === "localhost" || origin.hostname === "127.0.0.1") return;

    const selfWispUrl =
        (origin.protocol === "https:" ? "wss://" : "ws://") + origin.host + "/w";

    if (!Array.isArray(config.wispUrls)) config.wispUrls = [];

    const key = (url) => String(url).trim().toLowerCase().replace(/\/+$/, "");
    const existing = new Set(config.wispUrls.map(key));
    existing.add(key(config.wispUrl));
    if (existing.has(key(selfWispUrl))) return;

    config.wispUrls.unshift(selfWispUrl);
})();
